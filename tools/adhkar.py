COUNTS = [('مائة', 100), ('مئة', 100), ('عشر', 10), ('سبع', 7), ('أربع', 4), ('ثلاث', 3)]


def parse(raw):
    """Split the book's markup into [kind, text] segments: s said, n instruction,
    o wording from another narration, q Quran."""
    t = clean(raw)
    segs, buf, stack = [], '', []  # stack of (kind, opener)

    def kind():
        return stack[-1][0] if stack else 'n'

    def flush():
        nonlocal buf
        if buf:
            segs.append([kind(), buf])
        buf = ''

    i = 0
    while i < len(t):
        c = t[i]
        if t.startswith('((', i):
            flush(); stack.append(('s', '((')); i += 2; continue
        if t.startswith('))', i) and stack and stack[-1][1] == '((':
            flush(); stack.pop(); i += 2; continue
        if c == '﴿':
            flush(); stack.append(('q', c))
        elif c == '﴾':
            flush()
            if stack and stack[-1][1] == '﴿': stack.pop()
        elif c == '[':
            flush(); stack.append(('o' if kind() in 'sq' else 'n', c))
        elif c == ']':
            flush()
            if stack and stack[-1][1] == '[': stack.pop()
        elif c == '(':
            # a bare (…) around the whole text is what is said; inside, a remark
            flush(); stack.append(('s' if not stack and not any(k == 's' for k, _ in segs) else 'n', c))
        elif c == ')':
            flush()
            if stack and stack[-1][1] in '((': stack.pop()
        else:
            buf += c
        i += 1
    flush()
    out = []
    for k, x in segs:
        x = x.strip()
        if k in 'nq':
            x = x.strip(' .،,:؛-–')
        else:
            x = re.sub(r'^[.،,:؛\s]+', '', x).rstrip(' .')
        x = x.replace('*', ' ۝ ' if k == 'q' else '').replace('صلى الله عليه وسلم', 'ﷺ').replace('  ', ' ')
        if not re.search('[ء-ي]', x):
            continue
        if out and out[-1][0] == k:
            out[-1][1] += ' ' + x
        else:
            out.append([k, x])
    # "…قال" introducing what follows
    for a, b in zip(out, out[1:]):
        if a[0] == 'n' and re.search('(قال|يقول|قرأ|فيه|زيادة)( ﷺ)?$', HARAKAT.sub('', a[1])):
            a[1] += ':'
    return out


def count_of(segs, repeat):
    """The book writes counts as a trailing remark: (ثلاث مرات)."""
    c = repeat
    if segs and segs[-1][0] == 'n' and len(segs[-1][1]) < 45 and re.search('مر|ثلاثا|ثلاثًا', segs[-1][1]):
        for w, n in COUNTS:
            if w in segs[-1][1]:
                c = max(c, n)
                segs.pop()
                break
    return segs, c


