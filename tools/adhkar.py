def title(t):
    t = re.sub(r'\s+', ' ', HARAKAT.sub('', clean(t)))
    for a, b in TITLE_FIX.items():
        t = t.replace(a, b)
    return re.sub(r'\s*[?؟]$', '', t).strip()


def chapter(n):
    data = load(os.path.join(SRC, f'ch_{n}.json'))
    (name, rows), = data.items()
    items = []
    for x in rows:
        fix = FIX.get(x['ID'])
        if fix:
            segs, c = fix if isinstance(fix, tuple) else (fix, int(x.get('REPEAT') or 1))
        else:
            segs, c = count_of(parse(x['ARABIC_TEXT']), int(x.get('REPEAT') or 1))
        items.append(item(segs, c, REF.get(x['ID'])))
    return title(name), items


