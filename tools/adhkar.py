def load(path):
    raw = open(path, encoding='utf-8-sig').read()
    try:
        return json.loads(raw)
    except json.JSONDecodeError:
        return json.loads(re.sub(r'[\x00-\x1f]', ' ', raw))


def clean(t):
    t = unicodedata.normalize('NFKC', t).replace('ـ', '')
    return re.sub(r'\s+', ' ', t).strip()


# ---------------------------------------------------------------- quran

def aya_index(s, a):
    return next(i for i, (x, y) in enumerate(META['hafs']) if x == s and y == a)


def quran(s, a1, a2=None, basmala=False):
    """Uthmani text of s:a1-a2 (aya numbers kept: the mushaf font draws them as marks)."""
    i = aya_index(s, a1)
    text = ' '.join(HAFS['utext'][i:i + (a2 or a1) - a1 + 1])
    if basmala:
        text = HAFS['utext'][0].rsplit(' ', 1)[0] + ' ' + text
    return ['q', text]


def quran_from(s, a, word, a2=None):
    """Uthmani text of s:a from its word number `word` on (a dua quoting part of an aya)."""
    return ['q', ' '.join(quran(s, a, a2)[1].split(' ')[word:])]


